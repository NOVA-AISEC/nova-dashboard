import { defineConfig, loadEnv } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import path from 'path'

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), 'DAMA_')
  const apiPort = Number(process.env.DAMA_API_PORT ?? env.DAMA_API_PORT ?? 8787)
  if (!Number.isSafeInteger(apiPort) || apiPort < 1 || apiPort > 65535)
    throw new Error('Invalid DAMA_API_PORT.')
  return {
    plugins: [react(), tailwindcss()],
    resolve: {
      alias: {
        '@': path.resolve(__dirname, './src'),
      },
    },
    server: {
      host: '127.0.0.1',
      proxy: {
        '/api': {
          target: `http://127.0.0.1:${apiPort}`,
          changeOrigin: true,
        },
      },
    },
  }
})
